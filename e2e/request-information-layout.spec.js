import {captureBrowserEvidence} from '../scripts/ci/capture-evidence.mjs';
import {test,expect} from '@playwright/test';
import {INITIAL_ACCOUNTS} from '../src/demoAccounts.mjs';
import {DEMO_EQUIPMENT} from '../src/demoEquipment.mjs';
for(const theme of ['light','dark'])test(`lab information layout ${theme}: compact audit, initial focus and default equipment`,async({page})=>{
 await page.setViewportSize({width:1366,height:900});
 await page.addInitScript(({accounts,equipment,theme})=>{
  if(localStorage.getItem('layout-seeded'))return;localStorage.setItem('layout-seeded','yes');
  const request={id:'DEMO-LAYOUT-001',status:'已完成',requester:'測試委託者',productCode:'DEMO',testItem:'溫度試驗',demoFlow:{steps:[{id:'step1',label:'測試流程完成',at:'2026-11-01T01:00:00Z'}]},execution:{status:'已完成'}};
  localStorage.setItem('dqa-shared-demo-accounts-v1',JSON.stringify(accounts));
  localStorage.setItem('dqa-equipment-demo-v1',JSON.stringify(equipment));
  localStorage.setItem('dqa-global-theme',theme);
  localStorage.setItem('dqa-completed-flow-provisioned-v1',JSON.stringify({created:false}));
  localStorage.setItem('dqa-request-demo-v2',JSON.stringify([request]));
  localStorage.setItem('dqa_lab_demo_requests_v1','[]');
  localStorage.setItem('dqa_lab_demo_audit_v1',JSON.stringify([{id:'audit1',requestId:request.id,action:'完成試驗',actor:'測試工程師',time:'2026-11-01T01:00:00Z',reason:'測試完成',signature:'DEMO 模擬流程，非本人簽署'}]));
  sessionStorage.setItem('dqa-lab-account-id','U003');
 },{accounts:INITIAL_ACCOUNTS,equipment:DEMO_EQUIPMENT,theme});
 await page.goto('/lab/dashboard');
 await page.locator('.lab-sidebar').getByRole('button',{name:'設備狀態',exact:true}).click();
 await expect(page.locator('.equipment-counts>.summary-tile[aria-pressed=true]>span')).toHaveText('使用中');
 await page.locator('.lab-sidebar').getByRole('button',{name:'操作歷程',exact:true}).click();
 const row=page.locator('.lab-audit-panel tbody tr').filter({hasText:'DEMO-LAYOUT-001'}).first();
 expect((await row.boundingBox()).height).toBeLessThan(80);
 await row.getByText('查看簽名',{exact:true}).click();
 await expect(row.locator('.dqa-signature-history')).toBeVisible();
 await row.getByText('查看簽名',{exact:true}).click();
 await row.getByRole('button',{name:'DEMO-LAYOUT-001',exact:true}).click();
 const modal=page.getByRole('dialog');
 await expect(modal.getByRole('button',{name:'關閉委託單資訊',exact:true})).toBeFocused();
 expect(await modal.locator('.rq-request-detail-body').evaluate(el=>el.scrollTop)).toBe(0);
 await expect(page.getByRole('tooltip')).toHaveCount(0);
 expect(await modal.locator('.rq-demo-flow-section').evaluate(el=>parseFloat(getComputedStyle(el).paddingLeft))).toBeGreaterThanOrEqual(14);
 const history=modal.locator('.dqa-signature-history').first();
 expect(await history.evaluate(el=>parseFloat(getComputedStyle(el).paddingLeft))).toBeGreaterThanOrEqual(12);
 await captureBrowserEvidence(modal,{path:test.info().outputPath(`request-information-${theme}.png`)});
 await page.keyboard.press('Escape');await expect(modal).toHaveCount(0);
 await expect(row.getByRole('button',{name:'DEMO-LAYOUT-001',exact:true})).toBeFocused();
 await page.evaluate(async()=>{
  const requests=JSON.parse(localStorage.getItem('dqa-request-demo-v2'));
  requests[0].status='已結案';requests[0].signatureRecords=[{actorId:'U003',decision:'核准'}];
  localStorage.setItem('dqa-request-demo-v2',JSON.stringify(requests));
  const db=await new Promise((resolve,reject)=>{const open=indexedDB.open('dqa_lab_demo_reports',2);open.onsuccess=()=>resolve(open.result);open.onerror=()=>reject(open.error);});
  const report={requestId:requests[0].id,stage:'archived',confirmedAt:'2026-11-01T01:00:00Z',archivedAt:'2026-11-01T01:00:00Z',pdfName:'模擬文件.pdf',documentKind:'模擬報告'};
  await new Promise((resolve,reject)=>{const tx=db.transaction(['reports','reportIndex'],'readwrite');tx.objectStore('reports').put(report);tx.objectStore('reportIndex').put(report);tx.oncomplete=resolve;tx.onerror=()=>reject(tx.error);});db.close();
 });
 await page.reload();await page.locator('.lab-sidebar').getByRole('button',{name:'資料庫',exact:true}).click();
 const link=page.getByRole('button',{name:'DEMO-LAYOUT-001',exact:true});
 await expect(link).toHaveCSS('border-top-width','0px');await expect(link).toHaveCSS('padding-left','0px');
 await link.focus();expect(await link.evaluate(el=>parseFloat(getComputedStyle(el).outlineWidth))).toBeGreaterThanOrEqual(2);
 await link.click();await expect(page.getByRole('dialog')).toBeVisible();
 expect(await page.pageErrors()).toEqual([]);
});
